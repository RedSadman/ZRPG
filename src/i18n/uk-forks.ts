const STONES: PluralForms = {
  one: '{n} духовний камінь',
  few: '{n} духовні камені',
  many: '{n} духовних каменів',
  other: '{n} духовного каменя',
};
const POINTS: PluralForms = { one: '{n} очко внеску', few: '{n} очки внеску', many: '{n} очок внеску', other: '{n} очка внеску' };

const age = (e: { ageMonths: number }, c: NarrationContext) => `Тобі ${c.age(e.ageMonths)}.`;

/** What a real manual gave: a technique, or qi if there was nothing left to learn. */
const manual = (e: ForkResultEvent, c: NarrationContext) =>
  e.technique
    ? `Ти ${c.g('осягнув', 'осягнула')} техніку «${c.m.techniques[e.technique]}».`
    : `${e.amount ?? 0} ці влилися в меридіани.`;

const found = (e: ForkResultEvent, c: NarrationContext) => (e.item ? `${c.item(e.item, 'acc')} ${c.m.rankOf[e.item.rank]}` : '');

